#!/usr/bin/env node
// Writes apps/app/src/features/chant/psalmtone.generated.js: jgabc's
// psalmtone.node.js (github.com/bbloomf/jgabc, The Unlicense) as a module.
//
// The original is a browser script: it expects jQuery and timers, declares its
// work at the top level, and patches String.prototype. Here it is wrapped in
// one function that hands it stand-ins for what it expects and returns the two
// things Ember uses — the tones as data, and the routine that points a text to
// one. Nothing in it is rewritten, so a later jgabc can be taken by changing
// the commit below.
//
//   node scripts/vendor-psalmtone.mjs
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const commit = 'c2bdb18636089013340f153c1b3a1a014025afbb'
const url = `https://raw.githubusercontent.com/bbloomf/jgabc/${commit}/psalmtone.node.js`
const out = join(dirname(fileURLToPath(import.meta.url)), '../apps/app/src/features/chant/psalmtone.generated.js')

const source = await (await fetch(url)).text()
if (!source.includes('function applyPsalmTone')) throw new Error(`unexpected content at ${url}`)

const body = source
  // The built-in does the same and belongs to every string in the app.
  .replace(/^String\.prototype\.repeat = .*$/m, '')
  // Never called; without it the script adds nothing to String.prototype.
  .replace(/^String\.prototype\.format = function\(keys\)\{[\s\S]*?^\}$/m, '')

writeFileSync(
  out,
  `// GENERATED by scripts/vendor-psalmtone.mjs — do not edit.
// jgabc psalmtone.node.js @ ${commit}, released into the public domain (The Unlicense).
/* biome-ignore-all lint: vendored */
export default (function () {
  var exports = {}
  // Two names the script assigns without declaring, which a module, being strict, refuses.
  var temp, g_tones
  var require = function () {
    return {}
  }
  // It schedules a refresh of a word list it only needs in a browser.
  var setTimeout = function () {
    return 0
  }
  var clearTimeout = setTimeout
${body}
  return { applyPsalmTone: applyPsalmTone, tones: g_tones }
})()
`,
)
console.log(`wrote ${out}`)
